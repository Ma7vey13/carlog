// A regulation table on a photo or in a PDF → a chat AI → a CSV the import understands as is
// (the same columns as the downloadable template).

import { START_COMPONENTS } from './components';

export const TEMPLATE_HEADER = ['Название', 'Каждые, км', 'Каждые, мес', 'Тяжёлые, км', 'Тяжёлые, мес', 'Замена / проверка', 'Кто делает', 'Ключевые слова', 'Узел', 'Заметка'];

const EXAMPLE_ROWS = [
  ['Масло двигателя и масляный фильтр', '10000', '12', '7500', '6', 'Замена', 'Сервис', 'замена масла двигатель | масло моторное', 'Смазка двигателя', ''],
  ['Ремень привода агрегатов', '15000', '12', '', '', 'Проверка', 'Сервис', 'ремень генератора | ремень привода', 'ГРМ и приводные ремни', ''],
];

const csvCell = (v: string) => (/[;"\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v);

/** "Скачать шаблон таблицы": header and two example rows, semicolon-separated (opens in Excel). */
export function regulationTemplateCsv(): string {
  return '﻿' + [TEMPLATE_HEADER, ...EXAMPLE_ROWS].map((r) => r.map(csvCell).join(';')).join('\r\n') + '\r\n';
}

export function buildRegulationPrompt(): string {
  return [
    'На фото (или в PDF) — таблица регламента технического обслуживания автомобиля Hyundai Santa Fe 2.7 V6 из сервисной книжки или инструкции.',
    'Перепиши её в таблицу CSV с разделителем «;» и ровно такими колонками:',
    '',
    TEMPLATE_HEADER.join(';'),
    '',
    'Правила:',
    '1. Одна строка — одна операция. Ничего не придумывай: только то, что есть на фото. Сноски и оговорки — в колонку «Заметка».',
    '2. «Каждые, км» и «Каждые, мес» — целые числа без пробелов и единиц (15000, 12). Если в таблице «каждые 2 года» — пиши 24. Нет значения — оставь пусто.',
    '3. Если таблица — сетка «пробег по колонкам, в ячейках отметки» (З — заменить, П — проверить): интервал = шаг между отметками. Если у операции есть и З, и П — сделай две строки: «<операция> — замена» и «<операция> — проверка».',
    '4. «Тяжёлые, км» и «Тяжёлые, мес» — интервал для тяжёлых условий эксплуатации, если он указан отдельно; иначе пусто.',
    '5. «Замена / проверка» — одно слово: Замена или Проверка. «Кто делает» — Сервис или Сам.',
    '6. «Ключевые слова» — 1–3 варианта того, как эта работа обычно написана в заказ-наряде автосервиса, через « | », строчными буквами, только значимые слова. Например: замена масла двигатель | масло моторное.',
    `7. «Узел» — одно из: ${START_COMPONENTS.map((c) => c.name).join(', ')}. Если не подходит ни одно — пусто.`,
    '8. Ответ — только таблица в блоке ```csv … ``` без пояснений до и после.',
    '',
    'Пример двух строк:',
    '```csv',
    [TEMPLATE_HEADER, ...EXAMPLE_ROWS].map((r) => r.map(csvCell).join(';')).join('\n'),
    '```',
  ].join('\n');
}
